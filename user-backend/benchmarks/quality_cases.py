def quality_cases():
    original = cases()
    assert len(PROMPTS) == 100
    rows = [{**row, "id": "quality-" + row["id"], "prompt": prompt, "quality": "clear"}
            for row, prompt in zip(original[:100], PROMPTS)]
    rows.extend({**row, "id": "quality-" + row["id"]} for row in original[100:])
    for index, (prompt, reply, number) in enumerate(CONVERSATIONS, 1):
        rows.append({**original[number - 1], "id": f"conversation-{index:02}",
                     "prompt": prompt, "reply": reply, "expected_initial_status": ["clarification"],
                     "quality": "clarification"})
    return rows
